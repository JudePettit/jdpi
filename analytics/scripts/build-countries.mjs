// Builds analytics/lib/countries.js: ISO 3166-1 alpha-3, alpha-2 and numeric codes (numeric = world-atlas@2 feature ids)
// with a common English name and the other spellings PRP's datasets use, for the Data Analytics map.
//   node analytics/scripts/build-countries.mjs
// Codes come from National Analysis (national/data/index.json, World Bank names); the few territories world-atlas
// draws that National Analysis does not cover are added here, with Kosovo (no numeric code; matched by name).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const nat = JSON.parse(readFileSync(ROOT + 'national/data/index.json', 'utf8'));

const EXTRA = [
  ['ATA', 'AQ', '010', 'Antarctica'], ['ATF', 'TF', '260', 'French Southern and Antarctic Lands', 'Fr. S. Antarctic Lands'],
  ['ESH', 'EH', '732', 'Western Sahara', 'W. Sahara'], ['FLK', 'FK', '238', 'Falkland Islands', 'Falkland Is.', 'Falklands'],
  ['TWN', 'TW', '158', 'Taiwan', 'Republic of China', 'Chinese Taipei'], ['XKX', 'XK', '', 'Kosovo'],
  ['VAT', 'VA', '336', 'Vatican City', 'Holy See'], ['NRU', 'NR', '520', 'Nauru'], ['GGY', 'GG', '831', 'Guernsey'], ['NIU', 'NU', '570', 'Niue'], ['TKL', 'TK', '772', 'Tokelau'],
];
